"""Build the Zetaris Unified Semantic Layer (USL) for VESTING DAY and record what Zetaris returned.

Reads scripts/zetaris/usl.sql, where every block starts with "-- @step <kind> <name>", and sends
each block to the Zetaris REST API as ONE request, in order (the COMPILE block holds several
CREATE TABLE statements and must stay in one piece). Comment lines are not sent.

Writes:
  logs/zetaris-usl-build.jsonl       one line per step: the SQL, status, timing and what came back
  docs/ZETARIS_USL_EVIDENCE.md       the same, readable, generated by this script - never edited by hand

For every "query" step it also runs the same SQL on the SAMPLE_MODE copy of the councils'
published files and says whether Zetaris gave the same answer as the agent's own data.

Needs a live Zetaris: ZETARIS_REST_URL, ZETARIS_ORG_ID and ZETARIS_API_KEY in .env (the SSH
tunnel open if Zetaris is on a server). The key is sent in a header and never printed or written.

    uv run python scripts/zetaris/build_usl.py            # build and record
    uv run python scripts/zetaris/build_usl.py --dry-run  # list the steps, send nothing
"""

from __future__ import annotations

import argparse
import json
import re
import sqlite3
import sys
import time
import uuid
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Callable, Optional

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

import httpx  # noqa: E402

from app.adapters.datalayer import LocalDataLayer, _rows_from_payload  # noqa: E402

SQL_FILE = ROOT / "scripts" / "zetaris" / "usl.sql"
JSONL_OUT = ROOT / "logs" / "zetaris-usl-build.jsonl"
MD_OUT = ROOT / "docs" / "ZETARIS_USL_EVIDENCE.md"
USL = "lightning.metastore.vesting_day.west_surrey"
SOURCES = {"woking_pg": "Woking", "guildford_pg": "Guildford", "waverley_pg": "Waverley"}
KINDS = ("explore", "build", "check", "query", "dq")
ROWS_KEPT = 20
# "already exists" / "is existing" means a re-run found its object; "is not existing",
# "does not exist" and "not found" are real failures (Zetaris says "parent namespace : metastore
# is not existing" when a parent is missing).
EXISTS = re.compile(r"already\s+exist|\bexist", re.I)
MISSING = re.compile(r"not\s+exist|not\s+found|no\s+such", re.I)


def already_exists(error: str) -> bool:
    return bool(EXISTS.search(error)) and not MISSING.search(error)


@dataclass
class Step:
    kind: str
    name: str
    sql: str


def parse_steps(text: str) -> list[Step]:
    """Split usl.sql at its "-- @step" markers; each block is sent whole, without comment lines."""
    steps: list[Step] = []
    kind = name = None
    body: list[str] = []

    def flush() -> None:
        if kind is not None:
            sql = "\n".join(line for line in body if not line.lstrip().startswith("--")).strip()
            steps.append(Step(kind, name, sql))

    for line in text.splitlines():
        m = re.match(r"^--\s*@step\s+(\w+)\s+(\w+)\s*$", line)
        if m:
            flush()
            kind, name, body = m.group(1), m.group(2), []
            if kind not in KINDS:
                raise ValueError(f"unknown step kind {kind!r} in {name}")
        elif kind is not None:
            body.append(line)
    flush()
    return steps


# --- the agent's own answer, from the SAMPLE_MODE copy of the same published files ---------------

def sample_connection(data_dir: Path = ROOT / "data" / "sample") -> sqlite3.Connection:
    conn = LocalDataLayer(data_dir).conn
    conn.execute("CREATE TEMP TABLE IF NOT EXISTS council (council TEXT, zetaris_source TEXT)")
    if not conn.execute("SELECT COUNT(*) FROM council").fetchone()[0]:
        conn.executemany("INSERT INTO council VALUES (?, ?)", [(c, s) for s, c in SOURCES.items()])
    return conn


def sample_answer(conn: sqlite3.Connection, sql: str) -> list[dict[str, Any]]:
    """Run a USL query on the sample tables: the USL tables carry the same names and columns."""
    cur = conn.execute(sql.replace(USL + ".", ""))
    cols = [d[0] for d in cur.description]
    return [dict(zip(cols, r)) for r in cur.fetchall()]


def _norm(v: Any) -> str:
    if v is None or v == "":
        return ""
    try:
        return f"{float(v):.2f}"
    except (TypeError, ValueError):
        return str(v).strip()


def same_answer(live: list[dict[str, Any]], sample: list[dict[str, Any]]) -> bool:
    canon = lambda rows: sorted(json.dumps({k: _norm(v) for k, v in r.items()}, sort_keys=True) for r in rows)
    return canon(live) == canon(sample)


# --- talking to Zetaris ---------------------------------------------------------------------------

class Zetaris:
    def __init__(self, rest_url: str, org_id: str, api_key: str, client: Optional[httpx.Client] = None) -> None:
        self.url = rest_url.rstrip("/") + "/sql-editor/sqls/run"
        self.org_id = str(org_id)
        self.api_key = api_key
        self.client = client or httpx.Client()

    def run(self, sql: str, timeout: float, limit: int = 1000) -> dict[str, Any]:
        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "X-Org-ID": self.org_id,
            "X-Request-ID": str(uuid.uuid4()),
            "Content-Type": "application/json",
        }
        body = {"queryId": str(uuid.uuid4()), "sql": sql, "source": "SqlEditor", "limit": limit}
        r = self.client.post(self.url, headers=headers, json=body, timeout=timeout)
        out: dict[str, Any] = {"http_status": r.status_code}
        try:
            payload = r.json()
        except ValueError:
            payload = None
        if r.status_code >= 400:
            out["error"] = (r.text or "")[:800]
            return out
        out["rows"] = _rows_from_payload(payload) if payload is not None else []
        out["total"] = payload.get("total") if isinstance(payload, dict) else None
        return out


def run_steps(steps: list[Step], zetaris: Zetaris, log: Callable[[str], None] = lambda s: print(s, file=sys.stderr),
              sample: Optional[sqlite3.Connection] = None) -> list[dict[str, Any]]:
    """Send each step once. A failed build step stops the run (later steps need it); a build step
    that fails only because the object already exists (a re-run) does not."""
    results: list[dict[str, Any]] = []
    for i, st in enumerate(steps, 1):
        timeout = 300.0 if st.kind in ("build", "dq") else 120.0
        t0 = time.monotonic()
        rec: dict[str, Any] = {"step": i, "kind": st.kind, "name": st.name, "sql": st.sql}
        try:
            got = zetaris.run(st.sql, timeout=timeout)
        except httpx.HTTPError as e:
            got = {"http_status": None, "error": f"{type(e).__name__}: {e}"[:800]}
        rec["seconds"] = round(time.monotonic() - t0, 2)
        rec.update(got)
        rec["status"] = "error" if "error" in got else "success"
        if rec["status"] == "success":
            rec["row_count"] = len(got.get("rows", []))
            if st.kind == "query" and sample is not None:
                want = sample_answer(sample, st.sql)
                rec["sample_mode_rows"] = want
                rec["matches_sample_mode"] = same_answer(got["rows"], want)
        results.append(rec)
        note = f" | matches SAMPLE_MODE: {'yes' if rec.get('matches_sample_mode') else 'NO'}" if "matches_sample_mode" in rec else ""
        if rec["status"] == "success":
            detail = f"{rec.get('row_count', 0)} rows"
        else:  # show build errors in full (e.g. every mismatched column), others shortened
            detail = " ".join(rec["error"].replace("\\n", " ").split())[: 700 if st.kind == "build" else 200]
        log(f"[{i}/{len(steps)}] {st.kind} {st.name}: {rec['status']} in {rec['seconds']}s - {detail}{note}")
        if rec["status"] == "error" and st.kind == "build" and not already_exists(rec["error"]):
            log("stopping: a build step failed and the steps after it depend on it")
            break
    return results


# --- evidence -------------------------------------------------------------------------------------

def _cell(v: Any) -> str:
    s = "" if v is None else str(v)
    s = s.replace("|", "\\|").replace("\n", " ")
    return s if len(s) <= 120 else s[:117] + "..."


def _table(rows: list[dict[str, Any]]) -> str:
    if not rows:
        return "_no rows returned_\n"
    cols = list(rows[0].keys())
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(_cell(r.get(c)) for c in cols) + " |" for r in rows[:ROWS_KEPT]]
    if len(rows) > ROWS_KEPT:
        out.append(f"\n_{len(rows) - ROWS_KEPT} more rows not shown_")
    return "\n".join(out) + "\n"


def write_evidence(results: list[dict[str, Any]], started: str, jsonl: Path = JSONL_OUT, md: Path = MD_OUT) -> None:
    jsonl.parent.mkdir(parents=True, exist_ok=True)
    with jsonl.open("w", encoding="utf-8") as f:
        for r in results:
            keep = dict(r)
            keep["rows"] = (r.get("rows") or [])[:ROWS_KEPT]
            f.write(json.dumps({"run_started": started, **keep}, default=str) + "\n")

    ok = sum(1 for r in results if r["status"] == "success")
    lines = [
        "# Zetaris Unified Semantic Layer - live build evidence",
        "",
        f"Generated by `scripts/zetaris/build_usl.py` from a live run against Zetaris started {started}.",
        "Every result below is what Zetaris returned; nothing here is typed in by hand. The SQL of",
        "every step is in `scripts/zetaris/usl.sql`; the raw record is `logs/zetaris-usl-build.jsonl`.",
        "",
        f"{ok} of {len(results)} steps succeeded.",
        "",
        "| # | Kind | Step | Status | Seconds | Rows | Same answer as SAMPLE_MODE |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in results:
        match = {True: "yes", False: "no"}.get(r.get("matches_sample_mode"), "-")
        lines.append(f"| {r['step']} | {r['kind']} | {r['name']} | {r['status']} | {r['seconds']} | {r.get('row_count', '-')} | {match} |")
    lines.append("")
    for r in results:
        lines += [f"## {r['step']}. {r['kind']} - {r['name']}", "", "```sql", r["sql"], "```", ""]
        if r["status"] == "error":
            lines += [f"**Error** (HTTP {r.get('http_status')}):", "", "```", r["error"], "```", ""]
            continue
        lines.append(_table(r.get("rows") or []))
        if "matches_sample_mode" in r:
            verdict = "the same answer" if r["matches_sample_mode"] else "a DIFFERENT answer"
            lines += [f"The agent's SAMPLE_MODE data gives {verdict}:", "", _table(r["sample_mode_rows"])]
    md.parent.mkdir(parents=True, exist_ok=True)
    md.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main(argv: Optional[list[str]] = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--dry-run", action="store_true", help="list the steps and send nothing")
    args = p.parse_args(argv)
    steps = parse_steps(SQL_FILE.read_text(encoding="utf-8"))
    if args.dry_run:
        for i, st in enumerate(steps, 1):
            print(f"{i:2}. {st.kind:8} {st.name}")
        return 0

    from app.config import Settings

    cfg = Settings()
    if not cfg.zetaris_api_key:
        print("ZETARIS_API_KEY is not set (or is still the .env.example placeholder). This script needs a live "
              "Zetaris; SAMPLE_MODE has none.", file=sys.stderr)
        return 2
    started = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    results = run_steps(steps, Zetaris(cfg.zetaris_rest_url, cfg.zetaris_org_id, cfg.zetaris_api_key), sample=sample_connection())
    write_evidence(results, started)
    failed = [r["name"] for r in results if r["status"] == "error"]
    print(f"wrote {MD_OUT.relative_to(ROOT)} and {JSONL_OUT.relative_to(ROOT)}; "
          f"{len(results) - len(failed)} of {len(results)} steps succeeded" + (f"; failed: {', '.join(failed)}" if failed else ""),
          file=sys.stderr)
    return 1 if any(r["status"] == "error" and r["kind"] == "build" for r in results) else 0


if __name__ == "__main__":
    raise SystemExit(main())
