"""Print one SQL script that builds and fills the three council databases.

Each council gets its own Postgres database - vd_woking, vd_guildford, vd_waverley - so
Zetaris sees three separate sources, the way three councils really keep their own systems.
The rows come from data/sample (the councils' published files, already mapped). Nothing
is merged.

Run on the Zetaris server from the repo root. Plain Python 3, nothing to install:

  python3 scripts/zetaris/build_load_sql.py \\
    | docker exec -i vd-postgres psql -U vd -d postgres -v reader_pw="$(cat /root/vd_reader.pw)"

It also creates vd_reader, the read-only login Zetaris uses. Its password comes in with
-v, so it is never in the repo or in this script. Safe to run again: it drops and rebuilds
the three databases.
"""

from __future__ import annotations

import csv
import io
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SAMPLE = HERE.parents[1] / "data" / "sample"
SCHEMA = HERE / "schema.sql"

# council name as it appears in the data -> its own database
DATABASES = {"Woking": "vd_woking", "Guildford": "vd_guildford", "Waverley": "vd_waverley"}
TABLES = (("spend", "spend.csv"), ("contracts", "contracts.csv"), ("policy_clause", "policy_clauses.csv"))
READER = "vd_reader"


def read_rows(name: str) -> tuple[list[str], list[dict[str, str]]]:
    with open(SAMPLE / name, newline="", encoding="utf-8") as fh:
        reader = csv.DictReader(fh)
        return list(reader.fieldnames or []), list(reader)


def copy_block(table: str, cols: list[str], rows: list[dict[str, str]]) -> str:
    # COPY in CSV mode: an empty unquoted value loads as NULL, same as before.
    buf = io.StringIO()
    writer = csv.writer(buf, lineterminator="\n")
    for row in rows:
        values = [row[c] for c in cols]
        if any(line.strip() == "\\." for v in values for line in v.splitlines()):
            sys.exit(f"{table}: a value would end the COPY early - fix the data first")
        writer.writerow(values)
    return f"COPY {table} ({', '.join(cols)}) FROM STDIN WITH (FORMAT csv);\n{buf.getvalue()}\\.\n"


def main() -> None:
    data = {table: read_rows(name) for table, name in TABLES}
    schema = SCHEMA.read_text(encoding="utf-8")
    out = sys.stdout

    out.write("-- generated by scripts/zetaris/build_load_sql.py - do not edit by hand\n")
    out.write("\\set ON_ERROR_STOP on\n")
    out.write("\\if :{?reader_pw}\n\\else\n")
    out.write("\\echo 'missing the reader password - add: -v reader_pw=\"$(cat /root/vd_reader.pw)\"'\n")
    out.write("\\quit\n\\endif\n")

    for db in DATABASES.values():
        out.write(f"DROP DATABASE IF EXISTS {db} WITH (FORCE);\n")
    out.write(f"DROP ROLE IF EXISTS {READER};\n")
    out.write(f"CREATE ROLE {READER} LOGIN PASSWORD :'reader_pw';\n")

    for council, db in DATABASES.items():
        out.write(f"CREATE DATABASE {db};\n")
        out.write(f"REVOKE CONNECT ON DATABASE {db} FROM PUBLIC;\n")
        out.write(f"GRANT CONNECT ON DATABASE {db} TO {READER};\n")
        out.write(f"\\connect {db}\n")
        out.write(schema + "\n")
        for table, _ in TABLES:
            cols, rows = data[table]
            out.write(copy_block(table, cols, [r for r in rows if r["council"] == council]))
        out.write(f"GRANT SELECT ON ALL TABLES IN SCHEMA public TO {READER};\n")
        out.write(
            f"SELECT '{db}' AS database, (SELECT count(*) FROM spend) AS spend, "
            "(SELECT count(*) FROM contracts) AS contracts, "
            "(SELECT count(*) FROM policy_clause) AS policy_clause;\n"
        )


if __name__ == "__main__":
    try:
        main()
    except BrokenPipeError:
        # psql stopped reading early (for example the password was missing); its own
        # message says why, so exit quietly instead of printing a Python traceback.
        os.dup2(os.open(os.devnull, os.O_WRONLY), sys.stdout.fileno())
        sys.exit(1)
